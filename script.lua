-- Định nghĩa một hàm để tính tổng của hai số
local function add(a, b)
    return a + b
end

-- Gọi hàm add với các số 3 và 7
local result = add(3, 7)

-- In kết quả ra màn hình
print("Kết quả của 3 + 7 là:", result)

